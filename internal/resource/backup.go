// Backup is immutable: changing its inputs creates a new snapshot of the data.
// Use a separate resource (and prevent_destroy when appropriate) to retain older backups.
type BackupResource struct{ client *client.Client }

type backupModel struct {
	ID                  types.String `tfsdk:"id"`
	OrgName             types.String `tfsdk:"org_name"`
	ClusterName         types.String `tfsdk:"cluster_name"`
	Name                types.String `tfsdk:"name"`
	BackupMethod        types.String `tfsdk:"backup_method"`
	BackupType          types.String `tfsdk:"backup_type"`
	Component           types.String `tfsdk:"component"`
	RetentionPeriod     types.String `tfsdk:"retention_period"`
	Parameters          types.Map    `tfsdk:"parameters"`
	SelectedObjectsJSON types.String `tfsdk:"selected_objects_json"`
	Status              types.String `tfsdk:"status"`
}

func NewBackupResource() resource.Resource { return &BackupResource{} }
func (r *BackupResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_backup"
}

func immutableString(description string, required, computed bool) schema.StringAttribute {
	return schema.StringAttribute{Description: description, Required: required, Optional: !required, Computed: computed,
		PlanModifiers: []planmodifier.String{stringplanmodifier.RequiresReplace()}}
}

func (r *BackupResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{Description: "A manual backup. Creation waits for Completed; destroy deletes the backup and its stored files. Changing inputs replaces the backup.", Attributes: map[string]schema.Attribute{
		"id":                    schema.StringAttribute{Computed: true, PlanModifiers: []planmodifier.String{stringplanmodifier.UseStateForUnknown()}},
		"org_name":              immutableString("Organization containing the source cluster.", true, false),
		"cluster_name":          immutableString("Source cluster name. The cluster must be Running before backup.", true, false),
		"name":                  immutableString("Backup name; generated by the API when omitted.", false, true),
		"backup_method":         immutableString("DolphinDB: native (full) or native-selective.", true, false),
		"backup_type":           immutableString("Backup type. The API defaults to Full; native-selective requires Selective.", false, true),
		"component":             immutableString("Source component; DolphinDB standalone or datanode.", false, false),
		"retention_period":      immutableString("Retention period, for example 7d.", false, true),
		"parameters":            schema.MapAttribute{Optional: true, ElementType: types.StringType, Description: "Parameters supported by the selected backup method.", PlanModifiers: []planmodifier.Map{mapplanmodifier.RequiresReplace()}},
		"selected_objects_json": immutableString("JSON array of recursive API selection nodes (type, name, selectedAll, children). Use jsonencode for database, table and partition selection.", false, false),
		"status":                schema.StringAttribute{Computed: true},
	}}
}

func (r *BackupResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}
	var ok bool
	r.client, ok = req.ProviderData.(*client.Client)
	if !ok {
		resp.Diagnostics.AddError("Unexpected resource client", fmt.Sprintf("Expected *client.Client, got %T", req.ProviderData))
	}
}

func (r *BackupResource) ValidateConfig(ctx context.Context, req resource.ValidateConfigRequest, resp *resource.ValidateConfigResponse) {
	var data backupModel
	resp.Diagnostics.Append(req.Config.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() || data.SelectedObjectsJSON.IsUnknown() {
		return
	}
	if data.BackupMethod.ValueString() == "native-selective" && !data.BackupType.IsUnknown() && data.BackupType.ValueString() != "Selective" {
		resp.Diagnostics.AddAttributeError(path.Root("backup_type"), "Selective backup type required", "Set backup_type = \"Selective\" for native-selective.")
	}
	if _, err := selectionNodes(data.SelectedObjectsJSON); err != nil {
		resp.Diagnostics.AddAttributeError(path.Root("selected_objects_json"), "Invalid selection", err.Error())
	}
}

func selectionNodes(value types.String) ([]admin.SelectiveObjectTreeNode, error) {
	if value.IsNull() {
		return nil, nil
	}
	var nodes []admin.SelectiveObjectTreeNode
	if err := json.Unmarshal([]byte(value.ValueString()), &nodes); err != nil {
		return nil, fmt.Errorf("expected a JSON array of selection nodes: %w", err)
	}
	if len(nodes) == 0 {
		return nil, fmt.Errorf("selection must contain at least one node; omit selected_objects_json for the entire backup")
	}
	var validate func([]admin.SelectiveObjectTreeNode) error
	validate = func(items []admin.SelectiveObjectTreeNode) error {
		for _, node := range items {
			if node.GetName() == "" || node.GetType() == "" || node.UnparsedObject != nil || len(node.AdditionalProperties) > 0 {
				return fmt.Errorf("every selection node requires type and name and may only contain selectedAll and children")
			}
			if err := validate(node.Children); err != nil {
				return err
			}
		}
		return nil
	}
	return nodes, validate(nodes)
}

func (r *BackupResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var data backupModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}
	body := admin.BackupCreate{BackupMethod: data.BackupMethod.ValueString(), Name: data.Name.ValueStringPointer(), Component: data.Component.ValueStringPointer(), RetentionPeriod: data.RetentionPeriod.ValueStringPointer()}
	if !data.BackupType.IsNull() && !data.BackupType.IsUnknown() {
		v := admin.BackupType(data.BackupType.ValueString())
		body.BackupType = &v
	}
	if !data.Parameters.IsNull() {
		resp.Diagnostics.Append(data.Parameters.ElementsAs(ctx, &body.Parameters, false)...)
	}
	nodes, err := selectionNodes(data.SelectedObjectsJSON)
	body.SelectedObjects = nodes
	if err != nil {
		resp.Diagnostics.AddError("Invalid selection", err.Error())
	}
	if resp.Diagnostics.HasError() {
		return
	}
	apiCtx, cancel := operationContext(ctx, r.client)
	defer cancel()
	if err := waitForRunningCluster(apiCtx, r.client, data.OrgName.ValueString(), data.ClusterName.ValueString()); err != nil {
		resp.Diagnostics.AddError("Source cluster is not ready", err.Error())
		return
	}
	backup, err := r.createBackup(apiCtx, &data, body)
	if err != nil {
		resp.Diagnostics.AddError("Create backup failed", err.Error())
		return
	}
	if backup.GetId() == "" {
		resp.Diagnostics.AddError("Missing backup ID", "The API accepted the backup but returned no ID.")
		return
	}
	data.refresh(backup)
	// Persist the ID before polling, including on failure/cancellation, so Terraform can clean it up.
	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
	err = pollDataProtection(apiCtx, 5*time.Second, func() (string, string, error) {
		b, _, err := r.getBackup(apiCtx, &data)
		if err == nil {
			data.refresh(b)
		}
		return string(b.Status), b.GetFailureReason(), err
	})
	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
	if err != nil {
		resp.Diagnostics.AddError("Backup did not complete", fmt.Sprintf("Backup %s: %s", data.ID.ValueString(), err))
	}
}

func (m *backupModel) refresh(b admin.Backup) {
	m.ID = types.StringValue(b.GetId())
	m.Name = types.StringValue(b.Name)
	m.BackupMethod = types.StringValue(b.BackupMethod)
	m.BackupType = types.StringValue(string(b.BackupType))
	m.RetentionPeriod = types.StringValue(b.RetentionPeriod)
	m.Status = types.StringValue(string(b.Status))
	// Selectors are creation inputs. The API converts them to engine parameters;
	// replacing the configured representation with that conversion would cause drift.
}

func (r *BackupResource) createBackup(ctx context.Context, data *backupModel, body admin.BackupCreate) (admin.Backup, error) {
	if r.client.IsAdminClient() {
		result, resp, err := admin.NewBackupApi(r.client.AdminClient()).CreateClusterBackup(ctx, data.OrgName.ValueString(), data.ClusterName.ValueString(), body)
		return result, apiError(resp, err)
	}
	var publicBody kbcloud.BackupCreate
	if err := convertAPI(body, &publicBody); err != nil {
		return admin.Backup{}, err
	}
	result, resp, err := kbcloud.NewBackupApi(r.client.Client()).CreateClusterBackup(ctx, data.OrgName.ValueString(), data.ClusterName.ValueString(), publicBody)
	if err = apiError(resp, err); err != nil {
		return admin.Backup{}, err
	}
	var backup admin.Backup
	err = convertAPI(result, &backup)
	return backup, err
}

func (r *BackupResource) getBackup(ctx context.Context, data *backupModel) (admin.Backup, *http.Response, error) {
	if r.client.IsAdminClient() {
		b, resp, err := admin.NewBackupApi(r.client.AdminClient()).GetBackup(ctx, data.OrgName.ValueString(), data.ID.ValueString())
		return b, resp, apiError(resp, err)
	}
	b, resp, err := kbcloud.NewBackupApi(r.client.Client()).GetBackup(ctx, data.OrgName.ValueString(), data.ID.ValueString())
	if err = apiError(resp, err); err != nil {
		return admin.Backup{}, resp, err
	}
	var result admin.Backup
	err = convertAPI(b, &result)
	return result, resp, err
}

func (r *BackupResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var data backupModel
	resp.Diagnostics.Append(req.State.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}
	apiCtx, cancel := operationContext(ctx, r.client)
	defer cancel()
	b, httpResp, err := r.getBackup(apiCtx, &data)
	if httpResp != nil && httpResp.StatusCode == http.StatusNotFound {
		resp.State.RemoveResource(ctx)
		return
	}
	if err != nil {
		resp.Diagnostics.AddError("Read backup failed", err.Error())
		return
	}
	// GET by ID intentionally includes historical, soft-deleted records on
	// release-2.3. The active list is the authority for continued existence.
	exists, err := r.backupExists(apiCtx, &data)
	if err != nil {
		resp.Diagnostics.AddError("List active backups failed", err.Error())
		return
	}
	if !exists {
		resp.State.RemoveResource(ctx)
		return
	}
	data.refresh(b)
	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}

func (r *BackupResource) Update(_ context.Context, _ resource.UpdateRequest, resp *resource.UpdateResponse) {
	resp.Diagnostics.AddError("Backup is immutable", "Changing backup inputs requires replacement.")
}

func (r *BackupResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var data backupModel
	resp.Diagnostics.Append(req.State.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}
	apiCtx, cancel := operationContext(ctx, r.client)
	defer cancel()
	var httpResp *http.Response
	var err error
	if r.client.IsAdminClient() {
		httpResp, err = admin.NewBackupApi(r.client.AdminClient()).DeleteBackup(apiCtx, data.OrgName.ValueString(), data.ID.ValueString())
	} else {
		httpResp, err = kbcloud.NewBackupApi(r.client.Client()).DeleteBackup(apiCtx, data.OrgName.ValueString(), data.ID.ValueString())
	}
	if httpResp != nil && httpResp.StatusCode == http.StatusNotFound {
		return
	}
	if err = apiError(httpResp, err); err != nil {
		resp.Diagnostics.AddError("Delete backup failed", err.Error())
		return
	}
	// The API removes the active record and initiates asynchronous file cleanup.
	err = waitUntil(apiCtx, 5*time.Second, func() (bool, error) {
		exists, err := r.backupExists(apiCtx, &data)
		return !exists, err
	})
	if err != nil {
		resp.Diagnostics.AddError("Backup deletion did not complete", err.Error())
	}
}

func (r *BackupResource) backupExists(ctx context.Context, data *backupModel) (bool, error) {
	const pageSize int32 = 100
	for page := int32(1); ; page++ {
		var ids []string
		if r.client.IsAdminClient() {
			list, response, err := admin.NewBackupApi(r.client.AdminClient()).ListBackups(ctx, admin.ListBackupsOptionalParameters{
				OrgName: data.OrgName.ValueStringPointer(), ClusterName: data.ClusterName.ValueStringPointer(),
				WithDeletedBackups: pointer.To(false), Page: &page, PageSize: pointer.To(pageSize),
			})
			if err := apiError(response, err); err != nil {
				return false, err
			}
			for _, backup := range list.Items {
				ids = append(ids, backup.GetId())
			}
		} else {
			list, response, err := kbcloud.NewBackupApi(r.client.Client()).ListBackups(ctx, data.OrgName.ValueString(), kbcloud.ListBackupsOptionalParameters{
				ClusterName: data.ClusterName.ValueStringPointer(), WithDeletedBackups: pointer.To(false),
				Page: &page, PageSize: pointer.To(pageSize),
			})
			if err := apiError(response, err); err != nil {
				return false, err
			}
			for _, backup := range list.Items {
				ids = append(ids, backup.GetId())
			}
		}
		for _, id := range ids {
			if id == data.ID.ValueString() {
				return true, nil
			}
		}
		if len(ids) < int(pageSize) {
			return false, nil
		}
	}
}

func operationContext(ctx context.Context, c *client.Client) (context.Context, context.CancelFunc) {
	auth := c.Ctx()
	if c.IsAdminClient() {
		auth = c.AdminCtx()
	}
	apiCtx, cancel := context.WithTimeout(auth, 30*time.Minute)
	stop := context.AfterFunc(ctx, cancel)
	return apiCtx, func() { stop(); cancel() }
}

func convertAPI(source, destination interface{}) error {
	b, err := json.Marshal(source)
	if err != nil {
		return err
	}
	return json.Unmarshal(b, destination)
}
func apiError(resp *http.Response, err error) error {
	if err != nil {
		return fmt.Errorf("%w %s", err, utils.GetRespErrorDetail(resp))
	}
	if !utils.IsHTTPSuccess(resp) {
		return fmt.Errorf("API request failed: %s", utils.GetRespErrorDetail(resp))
	}
	return nil
}

func waitUntil(ctx context.Context, interval time.Duration, get func() (bool, error)) error {
	for {
		if err := ctx.Err(); err != nil {
			return err
		}
		done, err := get()
		if err != nil || done {
			return err
		}
		timer := time.NewTimer(interval)
		select {
		case <-ctx.Done():
			timer.Stop()
			return ctx.Err()
		case <-timer.C:
		}
	}
}

func pollDataProtection(ctx context.Context, interval time.Duration, get func() (string, string, error)) error {
	return waitUntil(ctx, interval, func() (bool, error) {
		status, reason, err := get()
		if err != nil {
			return false, err
		}
		switch status {
		case "Completed":
			return true, nil
		case "", "New", "Pending", "Running", "InProgress":
			return false, nil
		default:
			return false, fmt.Errorf("%s: %s", status, strings.TrimSpace(reason))
		}
	})
}

